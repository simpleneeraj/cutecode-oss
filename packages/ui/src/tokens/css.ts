import { Appearance, readValue, type TokenValue } from "./appearance";
import { densities, Density } from "./density";
import { FontPairing, fontPairings } from "./fonts";
import { neutrals } from "./neutrals";
import { Palette, palettes } from "./palettes";
import { Style, styles } from "./styles";

type TokenSet = Record<string, TokenValue>;

type Declaration = [name: string, value: string];

type ThemeSelection = {
  style: Style;
  palette: Palette;
  font: FontPairing;
};

const defaults = {
  palette: Palette.Blue,
  style: Style.Tactile,
  font: FontPairing.System,
} satisfies ThemeSelection;

const densityMediaQuery = {
  [Density.Compact]: "(pointer: fine) and (min-width: 48rem)",
};

const banner = "/* Generated by scripts/build-tokens.ts from src/tokens. Run `yarn tokens:build`, do not edit. */";

export function toVariableName(key: string) {
  return `--${key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}`;
}

function readLightDeclarations(tokens: TokenSet): Declaration[] {
  return Object.entries(tokens).map(([key, value]) => [toVariableName(key), readValue(value, Appearance.Light)]);
}

function readDarkDeclarations(tokens: TokenSet): Declaration[] {
  return Object.entries(tokens).flatMap(([key, value]): Declaration[] => {
    if (typeof value === "string") {
      return [];
    }
    return [[toVariableName(key), value[Appearance.Dark]]];
  });
}

function renderBlock(selector: string, declarations: Declaration[]) {
  const lines = declarations.map(([name, value]) => `  ${name}: ${value};`);
  return [`${selector} {`, ...lines, "}"].join("\n");
}

function renderMediaBlock(query: string, block: string) {
  const lines = block.split("\n").map((line) => `  ${line}`);
  return [`@media ${query} {`, ...lines, "}"].join("\n");
}

function renderDensityBlock(selector: string, density: Density) {
  return renderBlock(selector, readLightDeclarations(densities[density]));
}

function renderDensityBlocks() {
  return [
    renderDensityBlock(":root", Density.Regular),
    renderMediaBlock(densityMediaQuery[Density.Compact], renderDensityBlock(":root", Density.Compact)),
    ...Object.values(Density).map((density) => renderDensityBlock(`[data-density="${density}"]`, density)),
  ];
}

function renderThemedBlocks(selector: string, tokens: TokenSet) {
  const darkDeclarations = readDarkDeclarations(tokens);
  const lightBlock = renderBlock(selector, readLightDeclarations(tokens));
  const isAppearanceIndependent = darkDeclarations.length === 0;
  if (isAppearanceIndependent) {
    return [lightBlock];
  }
  return [lightBlock, renderBlock(`.dark${selector}, .dark ${selector}`, darkDeclarations)];
}

function renderSelectionBlocks(selection: ThemeSelection) {
  const tokens = {
    ...neutrals,
    ...palettes[selection.palette],
    ...styles[selection.style],
    ...fontPairings[selection.font],
  };
  return [renderBlock(":root", readLightDeclarations(tokens)), renderBlock(".dark", readDarkDeclarations(tokens))];
}

export function renderThemeCss(selection: ThemeSelection) {
  return `${renderSelectionBlocks(selection).join("\n\n")}\n`;
}

export function renderTokensCss() {
  const blocks = [
    ...renderSelectionBlocks(defaults),
    ...Object.values(Palette).flatMap((palette) =>
      renderThemedBlocks(`[data-palette="${palette}"]`, palettes[palette]),
    ),
    ...Object.values(Style).flatMap((style) => renderThemedBlocks(`[data-style="${style}"]`, styles[style])),
    ...Object.values(FontPairing).flatMap((fontPairing) =>
      renderThemedBlocks(`[data-font="${fontPairing}"]`, fontPairings[fontPairing]),
    ),
    ...renderDensityBlocks(),
  ];
  return `${[banner, ...blocks].join("\n\n")}\n`;
}
